// 逐菜状态键：同一份菜单内唯一标识一道菜。
// 为什么不能只用菜名：7 天菜单最多 21 道，AI 可能给出两道同名菜（「米饭」「凉拌黄瓜」）。
// 以菜名为键会让两道菜共用一份状态——点第一道，第二道也变「已生成」，其菜谱永远看不到。
// 用「菜单内下标 + 菜名」：同一份菜单内下标稳定（菜单整体替换时才变，而那时状态本就整体重置），
// 且保留菜名便于调试阅读。键的计算集中在此，避免各处各自拼字符串导致不一致。
export function dishKey(index: number, name: string): string {
  return `${index}:${name}`
}
